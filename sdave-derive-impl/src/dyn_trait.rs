//! `#[sdave_dyn]` codegen: `dyn Trait` SDAVE support.
//!
//! [`expand_sdave_dyn`] is the whole generator. What the attribute accepts, what it
//! emits and what it requires is documented in `sdave-derive`'s `README.md`; the
//! conventions the generated code follows are in this crate's `README.md`.

use alloc::vec::Vec;

use proc_macro2::TokenStream as TokenStream2;
use quote::{format_ident, quote};
use syn::{ItemTrait, Type, TypeParamBound, punctuated::Punctuated, token::Comma};

use crate::{
    allocator_ident, payload_and_items, policy_ident, serialize_typed_method, signature_range,
    slices_type, unexpected_signature,
};

/// Whether `bound` is `Any`, i.e. a trait bound whose last path segment is `Any`
/// (matching both `Any` and `::core::any::Any`).
pub fn is_any_bound(bound: &TypeParamBound) -> bool {
    let TypeParamBound::Trait(bound) = bound else {
        return false;
    };
    bound
        .path
        .segments
        .last()
        .is_some_and(|segment| segment.ident == "Any")
}

/// The claimed concrete types' `TypeName::FULL` names as one
/// `&'static [&'static str]`, bound to `__SDAVE_SIGNATURES` in the function body it is
/// emitted into.
///
/// Every claimed type is a valid signature of a `dyn` channel, so a report that matched
/// none of them names them all. A named `const` item (rather than an inline `&[..]`) keeps
/// an associated const out of a promoted temporary.
fn signatures_const(types: &[&Type]) -> TokenStream2 {
    quote! {
        const __SDAVE_SIGNATURES: &[&'static str] =
            &[#(<#types as ::sdave_codec::TypeName>::FULL),*];
    }
}

/// Generate the `dyn Trait` codec impls for a `#[sdave_dyn]`-annotated trait.
///
/// # Errors
/// Returns an error when the trait is generic, or when the attribute claims no concrete
/// type: both leave nothing to (de)serialize, so they are refused at compile time rather
/// than emitting an impl that can never match.
pub fn expand_sdave_dyn(
    types: &Punctuated<Type, Comma>,
    mut item: ItemTrait,
) -> syn::Result<TokenStream2> {
    if let Some(param) = item.generics.params.first() {
        return Err(syn::Error::new_spanned(
            param,
            "sdave_dyn does not support generic traits",
        ));
    }
    if types.is_empty() {
        return Err(syn::Error::new_spanned(
            &item.ident,
            "sdave_dyn needs the concrete types to claim, e.g. #[sdave_dyn(TypeA, TypeB)]",
        ));
    }

    let ident = item.ident.clone();
    let vis = item.vis.clone();
    // A sealing marker implemented for exactly the claimed types. Adding it as a
    // supertrait turns any unclaimed `impl Trait for …` into a compile error
    // instead of a value that can be built yet never (de)serialized.
    let claim = format_ident!("__SdaveDynClaim_{}", ident.clone());

    let mut supertraits: Vec<TypeParamBound> = item.supertraits.iter().cloned().collect();
    // The concrete value is recovered from the trait object by downcasting, which
    // needs `Any` (and therefore `'static`) in the trait's supertraits.
    if !supertraits.iter().any(is_any_bound) {
        supertraits.push(syn::parse_quote!(::core::any::Any));
    }
    supertraits.push(syn::parse_quote!(#claim));
    item.supertraits = supertraits.into_iter().collect();

    let allocator = allocator_ident();
    let policy = policy_ident();
    let types: Vec<&Type> = types.iter().collect();
    let deserializer = quote!(__sdave_deserializer);
    // The payload is `NonEnvelop(concrete type name) ++ Envelop(value)`: one item to collect.
    let payload = payload_and_items(&deserializer, &quote!(final_buffer), 1);
    let signatures = signatures_const(&types);
    // What a `dyn` value reports when its concrete type cannot be claimed: the accepted type
    // names, plus the range caught — nothing appended yet (serialize), the payload that held
    // no tag, or the tag that matched nothing claimed.
    let valid_signatures = quote!(__SDAVE_SIGNATURES);
    let unclaimed_here = unexpected_signature(
        &valid_signatures,
        &quote!((
            ::sdave_codec::Offset::new(buffer.len()),
            ::sdave_codec::Offset::new(buffer.len()),
        )),
    );
    let missing_tag = unexpected_signature(&valid_signatures, &quote!(__sdave_payload));
    let unclaimed_tag = unexpected_signature(&valid_signatures, &signature_range());
    let serialize_typed = serialize_typed_method(&allocator, &policy);
    let slices = slices_type(&quote!(3));
    let slices_typed = slices_type(&quote!(6));

    Ok(quote! {
        /// Sealing marker generated by `#[sdave_dyn]`; not part of any public API.
        #[doc(hidden)]
        #[allow(non_camel_case_types)]
        #[diagnostic::on_unimplemented(
            message = "`{Self}` is not claimed by this `#[sdave_dyn]` trait",
            note = "list it in the attribute: `#[sdave_dyn(..., {Self})]`"
        )]
        #vis trait #claim {}

        #(impl #claim for #types {})*

        #item

        impl ::sdave_codec::TypeName for dyn #ident + 'static {
            const FULL: &'static str = ::core::concat!(
                ::core::module_path!(),
                "::dyn ",
                ::core::stringify!(#ident),
            );
        }

        impl<#allocator> ::sdave_codec::Serialize<u8, #allocator> for dyn #ident + 'static
        where
            #allocator: ::core::alloc::Allocator + ::core::clone::Clone,
            #(#types: ::sdave_codec::Serialize<u8, #allocator> + ::sdave_codec::TypeName + #ident + 'static,)*
        {
            const SLICES: usize = 3;
            type Slices = #slices;
            type SlicesTyped = #slices_typed;

            unsafe fn serialize<#policy: ::sdave_codec::NamePolicy>(
                &self,
                buffer: &mut ::sdave_codec::__private::Vec<u8, #allocator>,
                variant: ::sdave_codec::Variant,
                strategy: ::sdave_codec::Strategy,
                limiter_pairs: &mut [::sdave_codec::LimiterPair<'_, u8, #allocator>],
            ) -> ::core::result::Result<Self::Slices, ::sdave_codec::Error> {
                let __sdave_any: &(dyn ::core::any::Any + 'static) = self;
                #(
                    if let ::core::option::Option::Some(__sdave_value) =
                        __sdave_any.downcast_ref::<#types>()
                    {
                        let __sdave_head = buffer.len();
                        let __sdave_typed = unsafe {
                            <#types as ::sdave_codec::Serialize<u8, #allocator>>::serialize_typed::<#policy>(
                                __sdave_value,
                                buffer,
                                ::sdave_codec::Name {
                                    head_offset: ::sdave_codec::Offset::new(__sdave_head),
                                    tail_offset: ::sdave_codec::Offset::new(__sdave_head),
                                },
                                variant,
                                strategy,
                                limiter_pairs,
                            )?
                        };
                        return unsafe {
                            ::sdave_codec::flatten_typed_envelop(
                                buffer,
                                __sdave_head,
                                __sdave_typed,
                            )
                        };
                    }
                )*
                #signatures
                ::core::result::Result::Err(#unclaimed_here)
            }

            #serialize_typed
        }

        impl<#allocator> ::sdave_codec::Deserialize<u8, #allocator>
            for ::sdave_codec::__private::Box<dyn #ident + 'static, #allocator>
        where
            #allocator: ::core::alloc::Allocator + ::core::clone::Clone,
            #(#types: ::sdave_codec::Deserialize<u8, #allocator, Type = #types> + ::sdave_codec::TypeName + #ident + 'static,)*
        {
            type Type = ::sdave_codec::__private::Box<dyn #ident + 'static, #allocator>;

            fn deserialize<#policy: ::sdave_codec::NamePolicy>(
                __sdave_deserializer: &mut ::sdave_codec::FlatDeserializer<'_, '_, u8, #allocator>,
                final_buffer: ::core::option::Option<::sdave_codec::Offset>,
                allocator: #allocator,
            ) -> ::core::result::Result<Self::Type, ::sdave_codec::Error> {
                #payload
                // Every claimed concrete type is a valid signature of this channel, so a
                // tag matching none of them reports them all.
                #signatures
                let ::core::option::Option::Some(::sdave_codec::Item::N { non_envelop }) =
                    &__sdave_items[0]
                else {
                    return ::core::result::Result::Err(#missing_tag);
                };
                let __sdave_name =
                    &__sdave_buffer[non_envelop.head_offset.get()..non_envelop.tail_offset.get()];
                #(
                    if ::sdave_codec::render_matches::<#policy, #types>(__sdave_name) {
                        // The concrete value's Envelop: from the tag's tail to the end of
                        // this payload (which is where a `Variant::V2` delimiter would
                        // still be unconfirmed).
                        let __sdave_value = (non_envelop.tail_offset, __sdave_payload.1);
                        let __sdave_concrete = unsafe {
                            ::sdave_codec::with_deserializer(
                                #deserializer,
                                __sdave_value,
                                |__sdave_concrete_deserializer| {
                                    <#types as ::sdave_codec::Deserialize<u8, #allocator>>::deserialize::<#policy>(
                                        __sdave_concrete_deserializer,
                                        ::core::option::Option::Some(__sdave_value.1),
                                        allocator.clone(),
                                    )
                                },
                            )?
                        };
                        let __sdave_boxed: ::sdave_codec::__private::Box<dyn #ident + 'static, #allocator> =
                            ::sdave_codec::__private::Box::new_in(__sdave_concrete, allocator);
                        return ::core::result::Result::Ok(__sdave_boxed);
                    }
                )*
                // The concrete type name matched nothing claimed.
                ::core::result::Result::Err(#unclaimed_tag)
            }
        }
    })
}
